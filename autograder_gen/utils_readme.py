from autograder_gen.config import Config, DEFAULT_LANGUAGE_RUNTIMES
from autograder_gen.utils_submission import STUDENT_ID_FALLBACK, eval_expected_output_script


def generate_readme_md(config: Config) -> str:
    readme_content = f"""# Autograder Package

Generated by [AutograderGen](https://github.com/alanlivio/autograder-gen)

- **Language**: {config.language}
- **Number of questions**: {len(config.questions)}
- **Total marking items**: {sum(len(q.marking_items) for q in config.questions)}
- **Total points**: {sum(sum(item.total_mark for item in q.marking_items) for q in config.questions)}
- **Required Files**: {', '.join(config.required_files) if config.required_files else 'None specified'}

## Package Structure

```
autograder.zip
├── setup.sh                # Environment setup script
├── run_autograder          # Main autograder execution script
├── run_tests.py            # Primary test runner using gradescope-utils
├── question_1_test.py      # Individual test files for each question
├── question_2_test.py
├── utils_submission.py     # Helper utilities for tests
└── README.md               # This file
```

## Test Types Supported

- **program_output_test**: Compares program output with expected results (both actual and expected output are trimmed before comparison; single-line inputs terminate with a newline)
- **function_signature_test**: Validates function signatures and parameters
- **function_return_test**: Tests function behavior with specific parameters (params, not inputs) and expected returns
- **function_output_test**: Tests function standard output with specific parameters (params, not inputs) and expected outputs
- **manual_review**: Qualitative manual review by instructor (e.g. written report, PDF)

## Questions"""

    for i, question in enumerate(config.questions, 1):
        readme_content += f"\n\n### Question {i}: {question.name}\n\n"

        question_points = sum(item.total_mark for item in question.marking_items)
        readme_content += f"**Total Points**: {question_points}\n\n"

        for j, item in enumerate(question.marking_items, 1):
            item_name = getattr(item, "name", "") or f"Marking Item {j}"
            readme_content += f"#### {j}. {item_name}\n\n"
            readme_content += f"- **Type**: {item.type.replace('_', ' ').title()}\n"
            readme_content += f"- **Target File**: {item.target_file}\n"
            readme_content += f"- **Points**: {item.total_mark}\n"

            if hasattr(item, "time_limit") and item.time_limit:
                readme_content += f"- **Time Limit**: {item.time_limit} seconds\n"

            if hasattr(item, "visibility") and item.visibility:
                visibility_map = {
                    "hidden": "Hidden from students",
                    "visible": "Visible to students immediately",
                    "after_due_date": "Visible after due date",
                    "after_published": "Visible after grades published",
                }
                readme_content += (
                    f"- **Visibility**: {visibility_map.get(item.visibility, item.visibility)}\n"
                )

            if item.type in ("function_return_test", "function_output_test"):
                if hasattr(item, "function_name") and item.function_name:
                    readme_content += f"- **Function**: `{item.function_name}()`\n"
                if hasattr(item, "test_cases") and item.test_cases:
                    readme_content += f"- **Test Cases**: {len(item.test_cases)} case(s)\n"

            elif item.type == "function_signature_test":
                if hasattr(item, "function_name") and item.function_name:
                    readme_content += f"- **Function**: `{item.function_name}()`\n"
                if hasattr(item, "expected_parameters") and item.expected_parameters:
                    readme_content += f"- **Expected Parameters**: `{item.expected_parameters}`\n"

            elif item.type == "program_output_test":
                readme_content += "- **Output Matching**: Output and expected output are trimmed before comparison\n"
                if hasattr(item, "expected_input") and item.expected_input:
                    input_lines = len(item.expected_input.splitlines())
                    readme_content += f"- **Input Lines**: {input_lines}\n"
                if hasattr(item, "expected_output") and item.expected_output:
                    output_lines = len(item.expected_output.splitlines())
                    readme_content += f"- **Expected Output Lines**: {output_lines}\n"

            elif item.type in ("git_submission_test", "git_submission_exists"):
                readme_content += "- **Requirement**: Submission must be made via a Git repository (GitLab or GitHub)\n"
            elif item.type in ("gitlab_submission_test", "gitlab_submission_exists"):
                readme_content += (
                    "- **Requirement**: Submission must be made via a GitLab repository\n"
                )
            elif item.type in ("github_submission_test", "github_submission_exists"):
                readme_content += (
                    "- **Requirement**: Submission must be made via a GitHub repository\n"
                )
    return readme_content


def generate_description_md(config: Config) -> str:
    runtime_info = DEFAULT_LANGUAGE_RUNTIMES.get(config.language.lower(), {})
    env_ver = runtime_info.get("version", config.language)
    lines = ["# Assessment Description", "", f"**Environment:** {env_ver}", ""]
    for i, question in enumerate(config.questions, 1):
        lines.append(f"## Question {i}: {question.name}")
        lines.append("")
        if hasattr(question, "description") and question.description:
            lines.append(question.description)
            lines.append("")
        question_points = sum(item.total_mark for item in question.marking_items)
        lines.append(f"**Total Points:** {question_points}")
        lines.append("")
        lines.append("### Marking Items")
        lines.append("")
        for visible_item_idx, item in enumerate(question.marking_items, 1):
            item_name = getattr(item, "name", "") or f"Marking Item {visible_item_idx}"
            lines.append(f"#### {visible_item_idx}. {item_name}")
            lines.append("")
            lines.append(f"- **Points:** {item.total_mark}")
            if item.type == "program_output_test":
                lines.append(
                    f"- **Requirement:** Program must produce specific output for given input in `{item.target_file}` (output and expected output are trimmed before comparison)."
                )
                if item.expected_input:
                    lines.append("")
                    lines.append("##### Example Input:")
                    lines.append("```")
                    lines.append(item.expected_input)
                    lines.append("```")
                exp_out = item.expected_output
                exp_script = getattr(item, "expected_output_script", None) or getattr(
                    question, "expected_output_script", None
                )
                if not exp_out and exp_script:
                    exp_out = eval_expected_output_script(
                        exp_script,
                        student_id=str(STUDENT_ID_FALLBACK),
                        expected_input=item.expected_input,
                    )
                if exp_out:
                    lines.append("")
                    lines.append("##### Expected Output:")
                    lines.append("```")
                    lines.append(exp_out)
                    lines.append("```")
            elif item.type == "function_signature_test":
                sig_details = []
                if getattr(item, "expected_parameters", ""):
                    sig_details.append(f"parameters `{item.expected_parameters}`")
                if getattr(item, "expected_return_type", ""):
                    sig_details.append(f"return type `{item.expected_return_type}`")
                detail_suffix = f" with {', '.join(sig_details)}" if sig_details else ""
                lines.append(
                    f"- **Requirement:** Function `{item.function_name}` in `{item.target_file}` must have correct signature{detail_suffix}."
                )
            elif item.type == "function_return_test":
                lines.append(
                    f"- **Requirement:** Function `{item.function_name}` in `{item.target_file}` must return expected values for given arguments."
                )
            elif item.type == "function_output_test":
                lines.append(
                    f"- **Requirement:** Function `{item.function_name}` in `{item.target_file}` must print expected standard output for given arguments."
                )
            elif item.type in ("git_submission_test", "git_submission_exists"):
                lines.append(
                    "- **Requirement:** Submission must be made via a Git repository (GitLab or GitHub)."
                )
            elif item.type in ("gitlab_submission_test", "gitlab_submission_exists"):
                lines.append("- **Requirement:** Submission must be made via a GitLab repository.")
            elif item.type in ("github_submission_test", "github_submission_exists"):
                lines.append("- **Requirement:** Submission must be made via a GitHub repository.")
            elif item.type == "manual_review":
                lines.append(
                    f"- **Requirement:** Qualitative evaluation of `{item.target_file}` (manual review by instructor)."
                    if item.target_file
                    else "- **Requirement:** Qualitative evaluation (manual review by instructor)."
                )
            lines.append("")
            visible_item_idx += 1
    md_content = "\n".join(lines).strip() + "\n"
    return md_content
